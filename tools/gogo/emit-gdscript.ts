import type { ComponentExpression, Literal } from "./model.ts";
import { COMPONENT_CLASSES } from "./validate.ts";

export function emitLiteral(literal: Literal): string {
    switch (literal.kind) {
        case "string-literal": return JSON.stringify(literal.value);
        case "integer-literal": return String(literal.value);
        case "boolean-literal": return literal.value ? "true" : "false";
        case "color-literal": return `Color("${literal.value}")`;
        case "number-literal": return literal.numberToken;
    }
}

export function emitGdscript(root: ComponentExpression, sourceName = "<source>"): string {
    const lines = ["# Generated by Gogo; do not edit.", `# Source: ${JSON.stringify(sourceName)}`,
        "extends EstragonSurface", "", "", "func _init() -> void:"];
    let next = 0;
    const emit = (node: ComponentExpression): string => {
        const variable = `component_${next++}`;
        const type = COMPONENT_CLASSES[node.component];
        lines.push(`\t# Gogo ${node.span.start.line}:${node.span.start.column}`,
            `\tvar ${variable}: ${type} = ${type}.new()`);
        for (const property of [...node.properties].sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
            lines.push(`\t${variable}.${property.name} = ${emitLiteral(property.value)}`);
        }
        for (const child of node.children) lines.push(`\t${variable}.add_child(${emit(child)})`);
        return variable;
    };
    const rootVariable = emit(root);
    lines.push(`\tset_root(${rootVariable})`);
    return lines.join("\n") + "\n";
}
